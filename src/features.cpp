QString Store::updateState(const std::function<QString(QJsonObject &)> &change) {
    QMutexLocker lock(&m_stateLock);
    QJsonObject state = managedState();
    if (QString error = change(state); !error.isEmpty())
        return error;
    return applyState(state);
}

QString Store::actMore(const QString &action, const QVariantList &args) {
    const QString a0 = args.value(0).toString();
    static const QRegularExpression appId("^[A-Za-z0-9._-]{1,128}$");

    if (action == "dock.pin" || action == "dock.unpin") {
        if (!appId.match(a0).hasMatch())
            return tr("Unknown app %1").arg(a0);
        return runOk("omarchy-dock", {action == "dock.pin" ? "pin" : "unpin", a0});
    }
    if (action == "dock.order") {
        QStringList ids;
        for (const QVariant &v : args) {
            if (!appId.match(v.toString()).hasMatch())
                return tr("Unknown app %1").arg(v.toString());
            ids << v.toString();
        }
        return runOk("omarchy-dock", QStringList{"pinned"} + ids);
    }

    if (action == "mime.set") {
        const QString app = args.value(1).toString();
        if (!appId.match(app).hasMatch())
            return tr("Unknown app %1").arg(app);
        for (const auto &[type, mimes] : fileTypes())
            if (type == a0)
                return runOk("xdg-mime", QStringList{"default", app + ".desktop"} + mimes);
        return tr("Unknown file type %1").arg(a0);
    }

    if (action == "webapp.add") {
        const QString url = args.value(1).toString(), icon = args.value(2).toString();
        static const QRegularExpression web(R"(^https?://[^\s"']+$)");
        if (a0.trimmed().isEmpty() || a0.contains('/') || a0.contains('\n'))
            return tr("Give the web app a name, without slashes");
        if (!web.match(url).hasMatch())
            return tr("The address starts with https://");
        if (!icon.isEmpty() && !web.match(icon).hasMatch())
            return tr("The icon is a web address of a PNG, or empty");
        return runOk("omarchy-webapp-install", {a0.trimmed(), url, icon.isEmpty() ? QStringLiteral("applications-internet") : icon}, 60000);
    }
    if (action == "webapp.remove") {
        if (a0.isEmpty() || a0.contains('/'))
            return tr("Unknown web app %1").arg(a0);
        return runOk("omarchy-webapp-remove", {a0}, 15000);
    }

    if (action == "theme.install") {
        static const QRegularExpression url(R"(^(https://[^\s'"]+|git@[A-Za-z0-9.-]+:[^\s'"]+)$)");
        if (!url.match(a0).hasMatch())
            return tr("Enter a git URL, like https://github.com/someone/omarchy-theme");
        return runOk("omarchy-theme-install", {a0}, 300000);
    }
    if (action == "theme.remove") {
        static const QRegularExpression slug("^[a-z0-9_][a-z0-9._+-]*$");
        if (!slug.match(a0).hasMatch() || !QFileInfo(m_paths.config + "/omarchy/themes/" + a0).isDir())
            return tr("Only themes you added can be removed");
        return runOk("omarchy-theme-remove", {a0}, 15000);
    }
    if (action == "wallpaper.add") {
        const ProcResult picked = run("omarchy-file-select", {"--title", tr("Choose pictures"), "--multiple",
                                                               "--extensions", "jpg jpeg png webp gif bmp"}, 600000);
        if (!picked.ok())
            return {};
        const QString theme = readText(m_paths.state + "/omarchy/current/theme.name").trimmed();
        if (theme.isEmpty() || theme.contains('/'))
            return tr("No theme is set");
        const QString dir = m_paths.config + "/omarchy/backgrounds/" + theme;
        QDir().mkpath(dir);
        for (const QString &path : picked.text().split('\n', Qt::SkipEmptyParts)) {
            const QString target = dir + "/" + QFileInfo(path).fileName();
            if (QFileInfo(path).isFile() && !QFileInfo::exists(target) && !QFile::copy(path, target))
                return tr("Could not copy %1").arg(path);
        }
        return {};
    }
    if (action == "wallpaper.openFolder")
        return launch("omarchy-theme-bg-install", {});

    if (action == "crash.unmute") {
        if (a0.isEmpty() || a0.contains('/'))
            return tr("Unknown program %1").arg(a0);
        return runOk("omarchy-crash-mute", {"--", a0, "off"});
    }

    if (action == "shortcut.add") {
        // args: keys, description, kind, value
        const QString keys = normalizeKeys(a0), kind = args.value(2).toString(), value = args.value(3).toString().trimmed();
        if (!Hypr::validKeys(keys))
            return tr("Press a key combination with at least one modifier, like Super + E");
        // A letter, digit, or symbol on its own (or with Shift) would stop
        // typing it in every app.
        const QString key = keys.section(" + ", -1);
        const bool typing = key.size() == 1 || key.startsWith("code:");
        if (typing && !keys.contains("SUPER") && !keys.contains("CTRL") && !keys.contains("ALT"))
            return tr("Add Super, Ctrl, or Alt, or that key stops typing in every app");
        if (!QStringList{"launch", "command", "webapp", "menu"}.contains(kind) || value.isEmpty() || value.contains('\n'))
            return tr("Choose what the shortcut does");
        if (kind == "webapp" && !value.startsWith("https://") && !value.startsWith("http://"))
            return tr("The address starts with https://");
        return updateState([&](QJsonObject &state) {
            QJsonArray bindings;
            for (const QJsonValue &b : state.value("bindings").toArray())
                if (normalizeKeys(b.toObject().value("keys").toString()) != keys)
                    bindings << b;
            bindings << QJsonObject{{"keys", keys}, {"description", args.value(1).toString().trimmed()}, {"kind", kind}, {"value", value}};
            state.insert("bindings", bindings);
            // A shortcut that was turned off is back in use.
            QJsonArray unbinds;
            for (const QJsonValue &k : state.value("unbinds").toArray())
                if (normalizeKeys(k.toString()) != keys)
                    unbinds << k;
            state.insert("unbinds", unbinds);
            return QString();
        });
    }
    if (action == "shortcut.remove" || action == "shortcut.enable" || action == "shortcut.disable") {
        const QString keys = normalizeKeys(a0);
        if (!Hypr::validKeys(keys))
            return tr("Unknown shortcut %1").arg(a0);
        return updateState([&](QJsonObject &state) {
            const QString list = action == "shortcut.remove" ? "bindings" : "unbinds";
            QJsonArray kept;
            for (const QJsonValue &v : state.value(list).toArray()) {
                const QString k = v.isObject() ? v.toObject().value("keys").toString() : v.toString();
                if (normalizeKeys(k) != keys)
                    kept << v;
            }
            if (action == "shortcut.disable")
                kept << keys;
            state.insert(list, kept);
            return QString();
        });
    }

    if (action == "autostart.add" || action == "autostart.remove") {
        const QString command = a0.trimmed();
        if (command.isEmpty() || command.contains('\n'))
            return tr("Enter a command or choose an app");
        return updateState([&](QJsonObject &state) {
            QJsonArray items;
            for (const QJsonValue &v : state.value("autostart").toArray())
                if (v.toObject().value("command").toString() != command)
                    items << v;
            if (action == "autostart.add")
                items << QJsonObject{{"command", command}, {"name", args.value(1).toString().isEmpty() ? command : args.value(1).toString()}};
            state.insert("autostart", items);
            return QString();
        });
    }

    if (action == "rule.add") {
        const QJsonObject rule = QJsonObject::fromVariantMap(args.value(0).toMap());
        if (rule.value("class").toString().isEmpty() && rule.value("title").toString().isEmpty())
            return tr("Choose an app the rule is for");
        return updateState([&](QJsonObject &state) {
            QJsonArray rules = state.value("windowRules").toArray();
            rules << rule;
            state.insert("windowRules", rules);
            return QString();
        });
    }
    if (action == "menu.searchEntries") {
        // args: the entries (none takes them out), and the group's label.
        // From the app they're a list; from the command line, JSON text.
        const QVariant given = args.value(0);
        QVariantList entries = given.toList();
        if (given.typeId() == QMetaType::QString)
            entries = QJsonDocument::fromJson(given.toString().toUtf8()).array().toVariantList();
        return setMenuSearch(entries, args.value(1).toString());
    }
    if (action == "rule.update") {
        const int index = a0.toInt();
        const QJsonObject rule = QJsonObject::fromVariantMap(args.value(1).toMap());
        if (rule.value("class").toString().isEmpty() && rule.value("title").toString().isEmpty())
            return tr("Choose an app the rule is for");
        return updateState([&](QJsonObject &state) {
            QJsonArray rules = state.value("windowRules").toArray();
            if (index < 0 || index >= rules.size())
                return tr("That rule is gone already");
            rules[index] = rule;
            state.insert("windowRules", rules);
            return QString();
        });
    }
    if (action == "rule.remove") {
        const int index = a0.toInt();
        return updateState([&](QJsonObject &state) {
            QJsonArray rules = state.value("windowRules").toArray();
            if (index < 0 || index >= rules.size())
                return tr("That rule is gone already");
            rules.removeAt(index);
            state.insert("windowRules", rules);
            return QString();
        });
    }

    if (action.startsWith("firewall.")) {
        // ufw needs root; pkexec puts the password prompt on screen.
        if (action == "firewall.enable")
            return runOk("pkexec", {"ufw", "--force", "enable"}, 120000);
        if (action == "firewall.disable")
            return runOk("pkexec", {"ufw", "disable"}, 120000);
        static const QRegularExpression port(R"(^\d{1,5}(:\d{1,5})?$)");
        const QString proto = args.value(1).toString();
        if (!port.match(a0).hasMatch() || !QStringList{"tcp", "udp", "any"}.contains(proto))
            return tr("A port is a number like 22, or a range like 6000:6010");
        const QString rule = proto == "any" ? a0 : a0 + "/" + proto;
        if (action == "firewall.allow")
            return runOk("pkexec", {"ufw", "allow", rule}, 120000);
        if (action == "firewall.delete") {
            const QString verb = args.value(2).toString();
            if (!QStringList{"allow", "deny", "reject", "limit"}.contains(verb))
                return tr("Unknown rule");
            return runOk("pkexec", {"ufw", "delete", verb, rule}, 120000);
        }
    }

    if (action.startsWith("printer.")) {
        static const QRegularExpression printer("^[A-Za-z0-9_.@-]{1,127}$");
        if (action == "printer.open")
            return launch("xdg-open", {"http://localhost:631/"});
        if (!printer.match(a0).hasMatch())
            return tr("Unknown printer %1").arg(a0);
        if (action == "printer.default")
            return runOk("lpoptions", {"-d", a0});
        if (action == "printer.test")
            return runOk("lp", {"-d", a0, "-t", "Settings test page", "/usr/share/cups/data/testprint"}, 30000);
        if (action == "printer.remove")
            return runOk("pkexec", {"lpadmin", "-x", a0}, 120000);
    }

    if (action == "snapshot.create")
        return runOk("pkexec", {"snapper", "-c", "root", "create", "-d", "Made in Settings"}, 120000);

    if (action == "managed.reset") {
        // args: kind, key
        const QString kind = a0, key = args.value(1).toString();
        if (kind == "monitor")
            return monitorAction("monitor.reset", {key});
        if (kind == "workspace")
            return monitorAction("monitors.workspaces", {QVariantMap{{key, QString()}}});
        if (kind == "primary")
            return monitorAction("monitors.primary", {QString()});
        if (kind == "binding")
            return actMore("shortcut.remove", {key});
        if (kind == "unbind")
            return actMore("shortcut.enable", {key});
        if (kind == "autostart")
            return actMore("autostart.remove", {key});
        if (kind == "rule")
            return actMore("rule.remove", {key});
        if (kind == "nightShift")
            return setNightShift("schedule", false);
        return updateState([&](QJsonObject &state) {
            if (kind == "hypr") {
                QJsonObject hypr = state.value("hypr").toObject();
                hypr.remove(key);
                state.insert("hypr", hypr);
            } else if (kind == "gesture") {
                state.remove("gestures");
            } else {
                return tr("Unknown change %1").arg(kind);
            }
            return QString();
        });
    }
    if (action == "managed.resetAll") {
        const bool scheduled = managedState().value("nightShift").toObject().value("schedule").toBool();
        const QString error = updateState([](QJsonObject &state) {
            for (const char *key : {"hypr", "monitors", "workspaces", "primary", "gestures", "bindings", "unbinds", "autostart", "windowRules", "nightShift"})
                state.remove(key);
            return QString();
        });
        if (error.isEmpty() && scheduled)
            return writeNightShift(QJsonObject());
        return error;
    }

    if (action == "settings.export") {
        // Into a folder the user picks, under a name with the date.
        QString dir = a0;
        if (dir.isEmpty()) {
            const ProcResult picked = run("omarchy-file-select", {"--title", tr("Choose where to save your settings"), "--directory"}, 600000);
            if (!picked.ok())
                return {};
            dir = picked.text().section('\n', 0, 0);
        }
        QString path = dir;
        if (QFileInfo(dir).isDir())
            path = dir + "/omarchy-settings-" + QDateTime::currentDateTime().toString("yyyy-MM-dd") + ".json";
        return saveText(path, QString::fromUtf8(QJsonDocument(exportSettings()).toJson(QJsonDocument::Indented)));
    }
    if (action == "settings.import") {
        QString path = a0;
        if (path.isEmpty()) {
            const ProcResult picked = run("omarchy-file-select", {"--title", tr("Choose a settings file"), "--extensions", "json"}, 600000);
            if (!picked.ok())
                return {};
            path = picked.text().section('\n', 0, 0);
        }
        QJsonParseError error;
        const QJsonDocument doc = QJsonDocument::fromJson(readText(path).toUtf8(), &error);
        if (error.error != QJsonParseError::NoError || doc.object().value("app").toString() != "omasettings")
            return tr("%1 is not a Settings export").arg(QFileInfo(path).fileName());
        return importSettings(doc.object());
    }

    if (action == "pane.reset")
        return resetPane(a0);
    if (action.startsWith("branding.") || action.startsWith("haptics.") || action.startsWith("restart.")
        || action.startsWith("menu.") || action.startsWith("reminder.") || action == "summon"
        || action == "plugin.clone" || action == "xcompose.edit")
        return actSystem(action, args);
    return tr("Unknown action %1").arg(action);
}

// Settings that belong to this machine rather than to the person: they stay
// behind when settings move to another computer.
// Power, displays, and Do Not Disturb are this machine's state too.
bool Store::isMachineSpecific(const QString &id) {
    static const QStringList ids{"security.gitName", "security.gitEmail", "general.dictation", "general.hostname", "general.timezone", "general.autoTime", "network.dns", "wifi.band",
                                 "wifi.enabled", "bluetooth.enabled", "display.brightness", "keyboard.backlight",
                                 "power.profile", "power.acProfile", "power.batteryProfile", "display.laptopScreen",
                                 "display.mirror", "display.nightLight", "notifications.doNotDisturb",
                                 "pointer.touchpad", "pointer.touchscreen", "lock.stayAwake"};
    return ids.contains(id) || id.startsWith("sound.");
}

QJsonObject Store::exportSettings() {
    QJsonObject settings;
    for (const Setting &s : m_settings) {
        if (isMachineSpecific(s.id))
            continue;
        const QVariant v = s.read ? s.read() : QVariant();
        if (v.isValid() && !v.isNull())
            settings.insert(s.id, QJsonValue::fromVariant(v));
    }
    const QJsonObject state = managedState();
    QJsonObject managed;
    for (const char *key : {"bindings", "unbinds", "autostart", "windowRules", "gestures", "nightShift"})
        if (state.contains(key))
            managed.insert(key, state.value(key));
    return QJsonObject{{"app", "omasettings"}, {"version", 1}, {"exported", QDateTime::currentDateTime().toString(Qt::ISODate)},
                       {"settings", settings}, {"managed", managed}};
}

QString Store::importSettings(const QJsonObject &doc) {
    QStringList failed;
    const QJsonObject managed = doc.value("managed").toObject();
    if (!managed.isEmpty()) {
        const QString error = updateState([&](QJsonObject &state) {
            for (auto it = managed.begin(); it != managed.end(); ++it)
                state.insert(it.key(), it.value());
            return QString();
        });
        if (!error.isEmpty())
            failed << error;
        else if (managed.value("nightShift").toObject().value("schedule").toBool())
            writeNightShift(managed.value("nightShift").toObject());
    }
    const QJsonObject settings = doc.value("settings").toObject();
    // Hyprland's options go into the generated file together, so Hyprland
    // reloads once rather than once for each.
    QVariantMap hypr;
    QStringList hyprLabels;
    for (auto it = settings.begin(); it != settings.end(); ++it) {
        const Setting *s = setting(it.key());
        if (!s || isMachineSpecific(it.key()) || it.key().startsWith("display.night"))
            continue;
        const QVariant value = it.value().toVariant();
        if (s->read && s->read() == value)
            continue;
        if (!s->hyprOption.isEmpty()) {
            QVariant v;
            if (QString error = normalize(*s, value, v); !error.isEmpty())
                failed << s->label + ": " + error;
            else if (!(s->read && s->read() == v)) {
                hypr.insert(s->hyprOption, v);
                hyprLabels << s->label;
            }
            continue;
        }
        if (QString error = write(it.key(), value); !error.isEmpty())
            failed << s->label + ": " + error;
    }
    if (!hypr.isEmpty())
        if (QString error = hyprSet(hypr); !error.isEmpty())
            failed << hyprLabels.join(", ") + ": " + error;
    return failed.isEmpty() ? QString() : tr("Some settings were not applied: %1").arg(failed.join("; "));
}
