static QString tr(const char *text) { return QCoreApplication::translate("Store", text); }

static QString readText(const QString &path) {
    QFile f(path);
    return f.open(QIODevice::ReadOnly) ? QString::fromUtf8(f.readAll()) : QString();
}

static QString saveText(const QString &path, const QString &text) {
    QDir().mkpath(QFileInfo(path).absolutePath());
    QSaveFile file(path);
    const QByteArray data = text.toUtf8();
    if (!file.open(QIODevice::WriteOnly) || file.write(data) != data.size() || !file.commit())
        return tr("Could not write %1").arg(path);
    return {};
}

static QStringList timesBetween(int fromHour, int toHour) {
    QStringList out;
    for (int h = fromHour; h <= toHour; ++h)
        for (int m : {0, 30})
            out << QStringLiteral("%1:%2").arg(h % 24, 2, 10, QChar('0')).arg(m, 2, 10, QChar('0'));
    return out;
}

static QVariantList asVariants(const QStringList &list) {
    QVariantList out;
    for (const QString &s : list)
        out << s;
    return out;
}

