// The [Desktop Entry] keys of a .desktop file. QSettings won't do: it reads
// ';' as a comment and ',' as a list, and both are ordinary in these files.
static QHash<QString, QString> desktopEntry(const QString &path) {
    QHash<QString, QString> out;
    bool inEntry = false;
    for (const QString &raw : readText(path).split('\n')) {
        const QString line = raw.trimmed();
        if (line.startsWith('[')) {
            inEntry = line == "[Desktop Entry]";
            continue;
        }
        const int eq = line.indexOf('=');
        if (!inEntry || line.startsWith('#') || eq <= 0)
            continue;
        const QString key = line.left(eq).trimmed();
        if (!out.contains(key))
            out.insert(key, line.mid(eq + 1).trimmed());
    }
    return out;
}

// Installed apps from their .desktop files, the user's first so their
// copies win.
QVariantList Store::apps() const {
    QStringList dirs{QDir::homePath() + "/.local/share/applications"};
    const QString dataDirs = qEnvironmentVariable("XDG_DATA_DIRS", "/usr/local/share:/usr/share");
    for (const QString &d : dataDirs.split(':', Qt::SkipEmptyParts))
        dirs << d + "/applications";
    dirs << "/var/lib/flatpak/exports/share/applications" << QDir::homePath() + "/.local/share/flatpak/exports/share/applications";
    QHash<QString, QVariantMap> found;
    for (const QString &dir : dirs) {
        QDirIterator it(dir, {"*.desktop"}, QDir::Files, QDirIterator::Subdirectories);
        while (it.hasNext()) {
            const QString path = it.next();
            const QString id = QDir(dir).relativeFilePath(path).chopped(8).replace('/', '-');
            if (found.contains(id))
                continue;
            const QHash<QString, QString> desktop = desktopEntry(path);
            QVariantMap app;
            app["id"] = id;
            app["name"] = desktop.value("Name");
            app["icon"] = desktop.value("Icon");
            app["exec"] = desktop.value("Exec");
            // The class its windows carry: what the entry says, or else its
            // file name, which Wayland apps use as their app id.
            app["wmClass"] = desktop.value("StartupWMClass", QFileInfo(path).completeBaseName());
            app["mime"] = desktop.value("MimeType").split(';', Qt::SkipEmptyParts);
            app["hidden"] = desktop.value("NoDisplay") == "true" || desktop.value("Hidden") == "true"
                            || desktop.value("Type") != "Application";
            found.insert(id, app);
        }
    }
    QVariantList out;
    for (const QVariantMap &app : found)
        if (!app.value("name").toString().isEmpty())
            out << app;
    std::sort(out.begin(), out.end(), [](const QVariant &a, const QVariant &b) {
        return a.toMap().value("name").toString().compare(b.toMap().value("name").toString(), Qt::CaseInsensitive) < 0;
    });
    return out;
}

static QString keysFor(int modmask, const QString &key) {
    QStringList parts;
    if (modmask & 64) parts << "SUPER";
    if (modmask & 4) parts << "CTRL";
    if (modmask & 8) parts << "ALT";
    if (modmask & 1) parts << "SHIFT";
    // Keycodes stay as Hyprland spells them (code:20); names are upper-case.
    parts << (key.startsWith("code:", Qt::CaseInsensitive) ? key.toLower() : key.toUpper());
    return parts.join(" + ");
}

// Keys as Hyprland reads them, in one spelling, so two ways of writing the
// same chord compare equal: modifiers in a fixed order, the key upper-case.
QString Store::normalizeKeys(const QString &keys) {
    const QStringList parts = keys.split('+');
    int mask = 0;
    QString key;
    for (QString p : parts) {
        p = p.trimmed().toUpper();
        if (p == "SUPER" || p == "WIN" || p == "MOD4") mask |= 64;
        else if (p == "CTRL" || p == "CONTROL") mask |= 4;
        else if (p == "ALT" || p == "MOD1") mask |= 8;
        else if (p == "SHIFT") mask |= 1;
        else key = p.startsWith("CODE:") ? p.toLower() : p;
    }
    return keysFor(mask, key);
}

// The window rules Omarchy and the user's own Hyprland files set up, read
// by running those files in Hyprland's own Lua with an o.window that only
// records what it's given: the files are code (locals, loops, helpers), so
// reading them as text would miss rules. The chunks see nothing but that
// stand-in and the pure string and table libraries.
static const char *ruleReader = R"lua(
local out = {}
local function inert() return setmetatable({}, { __index = function() return inert end, __call = inert }) end
for _, f in ipairs(FILES) do
  local o = setmetatable({}, { __index = function() return inert end })
  local function record(match, rules)
    if type(match) == "string" then match = { class = match } end
    if type(match) == "table" and type(rules) == "table" then
      out[#out + 1] = { file = f.label, source = f.source, match = match, rules = rules }
    end
  end
  o.window = record
  o.transparent_window = function(match) record(match, { transparent = true }) end
  local env = setmetatable({ o = o, hl = inert(), require = function() return inert() end, print = inert },
    { __index = { string = string, table = table, math = math, ipairs = ipairs, pairs = pairs, next = next,
                  tostring = tostring, tonumber = tonumber, type = type, select = select, unpack = table.unpack } })
  local chunk = loadfile(f.path, "t", env)
  if chunk then pcall(chunk) end
end
local function json(v)
  local t = type(v)
  if t == "table" then
    local parts = {}
    if #v > 0 or next(v) == nil then
      for _, x in ipairs(v) do parts[#parts + 1] = json(x) end
      return "[" .. table.concat(parts, ",") .. "]"
    end
    for k, x in pairs(v) do parts[#parts + 1] = json(tostring(k)) .. ":" .. json(x) end
    return "{" .. table.concat(parts, ",") .. "}"
  elseif t == "string" then
    return '"' .. v:gsub('[%c"\\]', function(c) return string.format("\\u%04x", c:byte()) end) .. '"'
  elseif t == "number" and v == v and v ~= math.huge and v ~= -math.huge then return tostring(v)
  elseif t == "boolean" then return tostring(v) end
  return "null"
end
return json(out)
)lua";

QVariantList Store::otherWindowRules() const {
    if (!m_paths.hyprland)
        return {};
    struct File { QString path, label, source; };
    QList<File> files{{m_paths.omarchy + "/default/hypr/windows.lua", "windows.lua", "omarchy"}};
    const QDir appRules(m_paths.omarchy + "/default/hypr/apps");
    for (const QString &name : appRules.entryList({"*.lua"}, QDir::Files, QDir::Name))
        files << File{appRules.filePath(name), "apps/" + name, "omarchy"};
    // The user's own files, but not the one Settings writes: its rules are
    // listed as Settings' own.
    const QDir own(m_paths.config + "/hypr");
    for (const QString &name : own.entryList({"*.lua"}, QDir::Files, QDir::Name))
        if (name != "omasettings.lua" && name != "hyprland.lua")
            files << File{own.filePath(name), "~/.config/hypr/" + name, "config"};

    QString code = "local FILES = {\n";
    for (const File &f : files)
        code += "{ path = " + Hypr::luaString(f.path) + ", label = " + Hypr::luaString(f.label) + ", source = "
                + Hypr::luaString(f.source) + " },\n";
    code += "}\n" + QString::fromUtf8(ruleReader);
    const QJsonArray found = QJsonDocument::fromJson(run("hyprctl", {"repl", code}, 8000).out).array();

    // What a tag stands for (Omarchy floats and sizes windows tagged
    // floating-window), so a rule that only adds the tag reads as what it does.
    QHash<QString, QJsonObject> tagged;
    for (const QJsonValue &v : found) {
        const QJsonObject match = v.toObject().value("match").toObject();
        const QJsonObject rules = v.toObject().value("rules").toObject();
        if (match.size() == 1 && match.value("tag").isString())
            for (auto it = rules.begin(); it != rules.end(); ++it)
                tagged[match.value("tag").toString()].insert(it.key(), it.value());
    }

    const QVariantList installed = apps();
    QVariantList out;
    for (const QJsonValue &v : found) {
        const QJsonObject r = v.toObject();
        const QJsonObject match = r.value("match").toObject();
        // Only rules for particular apps or windows: not tag groups, not
        // every window, not XWayland internals.
        bool forApp = !match.isEmpty();
        for (auto it = match.begin(); it != match.end(); ++it)
            forApp = forApp && (it.key() == "class" || it.key() == "title") && it.value().isString()
                     && !QStringList{"", "^$", ".*", "^.*$"}.contains(it.value().toString());
        if (!forApp)
            continue;
        QJsonObject rules = r.value("rules").toObject();
        const QString tag = rules.value("tag").toString();
        const QJsonObject fromTag = tag.startsWith('+') ? tagged.value(tag.mid(1)) : QJsonObject();
        for (auto it = fromTag.begin(); it != fromTag.end(); ++it)
            if (!rules.contains(it.key()))
                rules.insert(it.key(), it.value());
        rules.remove("tag");
        if (rules.isEmpty())
            continue;
        const QString cls = match.value("class").toString(), title = match.value("title").toString();
        const QString file = r.value("file").toString();
        // Omarchy sometimes sets one window's rules a line at a time.
        if (!out.isEmpty()) {
            QVariantMap last = out.last().toMap();
            if (last.value("class") == cls && last.value("title") == title && last.value("file") == file) {
                QVariantMap merged = last.value("rules").toMap();
                merged.insert(rules.toVariantMap());
                last.insert("rules", merged);
                out.last() = last;
                continue;
            }
        }
        QVariantMap rule{{"class", cls}, {"title", title}, {"rules", rules.toVariantMap()}, {"file", file},
                         {"source", r.value("source").toString()}};
        rule.insert(appForPattern(installed, cls));
        out << rule;
    }
    return out;
}

// The installed apps a class pattern names: one app's name and icon, or
// the names of the few a pattern for several (every browser) covers.
QVariantMap Store::appForPattern(const QVariantList &installed, const QString &pattern) {
    if (pattern.isEmpty())
        return {};
    const QRegularExpression re(QRegularExpression::anchoredPattern(pattern));
    if (!re.isValid())
        return {};
    QStringList names;
    QString icon;
    for (const QVariant &a : installed) {
        const QVariantMap app = a.toMap();
        if (app.value("hidden").toBool())
            continue;
        // Hyprland matches the whole class.
        const QString wmClass = app.value("wmClass").toString(), id = app.value("id").toString();
        if ((!wmClass.isEmpty() && re.match(wmClass).hasMatch()) || re.match(id).hasMatch()) {
            if (!names.contains(app.value("name").toString()))
                names << app.value("name").toString();
            icon = app.value("icon").toString();
        }
    }
    if (names.isEmpty())
        return {};
    if (names.size() == 1)
        return {{"appName", names.first()}, {"appIcon", icon}};
    return {{"appNames", names}};
}

QVariant Store::listMore(const QString &name) {
    if (name == "apps") {
        QVariantList out;
        for (const QVariant &a : apps())
            if (!a.toMap().value("hidden").toBool())
                out << a;
        return out;
    }
    if (name == "fileTypes") {
        const QVariantList all = apps();
        QVariantList out;
        for (const auto &[type, mimes] : fileTypes()) {
            QVariantList candidates;
            for (const QVariant &a : all) {
                const QStringList appMimes = a.toMap().value("mime").toStringList();
                const bool handles = std::any_of(mimes.begin(), mimes.end(), [&](const QString &m) { return appMimes.contains(m); });
                if (handles)
                    candidates << QVariantMap{{"id", a.toMap().value("id")}, {"name", a.toMap().value("name")}};
            }
            QString current = output("xdg-mime", {"query", "default", mimes.first()});
            if (current.endsWith(".desktop"))
                current.chop(8);
            out << QVariantMap{{"type", type}, {"current", current}, {"apps", candidates}};
        }
        return out;
    }
    if (name == "webapps") {
        QVariantList out;
        static const QRegularExpression url(R"((https?://[^\s"']+))");
        QDir dir(QDir::homePath() + "/.local/share/applications");
        for (const QString &file : dir.entryList({"*.desktop"}, QDir::Files, QDir::Name)) {
            const QHash<QString, QString> desktop = desktopEntry(dir.filePath(file));
            const QString exec = desktop.value("Exec");
            if (!exec.contains("omarchy-launch-webapp") && !exec.contains("omarchy-webapp-handler"))
                continue;
            out << QVariantMap{{"name", file.chopped(8)}, {"title", desktop.value("Name")},
                               {"url", url.match(exec).captured(1)}, {"icon", desktop.value("Icon")}};
        }
        return out;
    }
    if (name == "dock") {
        QHash<QString, QString> names;
        for (const QVariant &a : apps())
            names.insert(a.toMap().value("id").toString(), a.toMap().value("name").toString());
        QVariantList out;
        for (const QString &id : output("omarchy-dock", {"pinned"}).split('\n', Qt::SkipEmptyParts))
            out << QVariantMap{{"id", id}, {"name", names.value(id, id)}};
        return out;
    }
    if (name == "wifiBand") {
        QVariantMap out;
        for (const QString &line : output("omarchy-network-band", {}, 10000).split('\n')) {
            const QString key = line.section('\t', 0, 0), value = line.section('\t', 1).trimmed();
            if (key == "available")
                out["available"] = value.split(' ', Qt::SkipEmptyParts);
            else if (!key.isEmpty())
                out[key] = value;
        }
        return out;
    }
    if (name == "power") {
        return QVariantMap{{"hibernation", run("omarchy-hibernation-available", {}, 5000).ok()},
                           {"keyboardBacklight", !keyboardBacklight().isEmpty()},
                           {"touchscreen", !output("omarchy-hw-touchscreen", {}).isEmpty()}};
    }
    if (name == "crashMutes") {
        const QString text = output("omarchy-crash-mute", {});
        QVariantList out;
        if (!text.startsWith("No programs"))
            for (const QString &p : text.split('\n', Qt::SkipEmptyParts))
                out << p;
        return out;
    }
    if (name == "shortcuts") {
        // Every binding Hyprland has, by its keys, so the editor can say
        // what a new shortcut would replace.
        QVariantList bound;
        for (const QJsonValue &v : QJsonDocument::fromJson(run("hyprctl", {"-j", "binds"}).out).array()) {
            const QJsonObject b = v.toObject();
            QString key = b.value("key").toString();
            if (key.isEmpty() && b.value("keycode").toInt() > 0)
                key = "code:" + QString::number(b.value("keycode").toInt());
            if (b.value("mouse").toBool() || b.value("release").toBool() || key.isEmpty())
                continue;
            const QString keys = keysFor(b.value("modmask").toInt(), key);
            bound << QVariantMap{{"keys", keys}, {"description", b.value("description").toString()}};
        }
        const QJsonObject state = managedState();
        return QVariantMap{{"bound", bound},
                           {"custom", state.value("bindings").toArray().toVariantList()},
                           {"disabled", state.value("unbinds").toArray().toVariantList()},
                           {"listed", parseKeybindings(output("omarchy-menu-keybindings", {"--print"}, 10000))}};
    }
    if (name == "loginItems") {
        // The user's own autostart.lua is theirs; it is shown, not edited.
        QVariantList fromFile;
        static const QRegularExpression call(R"(^\s*o\.(launch|exec)_on_start\(\s*["'](.+)["']\s*\))");
        for (const QString &line : readText(m_paths.config + "/hypr/autostart.lua").split('\n')) {
            const auto m = call.match(line);
            if (m.hasMatch())
                fromFile << m.captured(2);
        }
        return QVariantMap{{"managed", managedState().value("autostart").toArray().toVariantList()}, {"fromFile", fromFile}};
    }
    if (name == "menuSearch")
        return QVariantMap{{"on", menuSearchOn()}};
    if (name == "windowRules") {
        QVariantList classes;
        QStringList seen;
        for (const QJsonValue &v : QJsonDocument::fromJson(run("hyprctl", {"-j", "clients"}).out).array()) {
            const QString cls = v.toObject().value("class").toString();
            if (!cls.isEmpty() && !seen.contains(cls)) {
                seen << cls;
                classes << QVariantMap{{"class", cls}, {"title", v.toObject().value("title").toString()}};
            }
        }
        // Settings' own rules, with the app each one is for.
        const QVariantList installed = apps();
        QVariantList own;
        for (const QVariant &r : managedState().value("windowRules").toArray().toVariantList()) {
            QVariantMap rule = r.toMap();
            rule.insert(appForPattern(installed, rule.value("class").toString()));
            own << rule;
        }
        return QVariantMap{{"rules", own}, {"windows", classes}, {"others", otherWindowRules()}};
    }
    if (name == "firewall") {
        // ufw keeps its rules world-readable, so showing them needs no
        // password; changing them does.
        QVariantList rules;
        static const QRegularExpression tuple(R"(^### tuple ### (\S+) (\S+) (\S+) (\S+) (\S+) (\S+) (\S+))");
        for (const QString &file : {QStringLiteral("/etc/ufw/user.rules"), QStringLiteral("/etc/ufw/user6.rules")})
            for (const QString &line : readText(file).split('\n')) {
                const auto m = tuple.match(line);
                if (!m.hasMatch())
                    continue;
                const QVariantMap rule{{"action", m.captured(1)}, {"proto", m.captured(2)}, {"port", m.captured(3)},
                                       {"from", m.captured(6)}, {"direction", m.captured(7)}, {"v6", file.endsWith("6.rules")}};
                // The same rule for IPv4 and IPv6 is one rule to a person.
                if (std::none_of(rules.begin(), rules.end(), [&](const QVariant &r) {
                        const QVariantMap x = r.toMap();
                        return x["action"] == rule["action"] && x["proto"] == rule["proto"] && x["port"] == rule["port"]
                               && x["direction"] == rule["direction"];
                    }))
                    rules << rule;
            }
        const bool installed = !QStandardPaths::findExecutable("ufw").isEmpty();
        const bool configured = readText("/etc/ufw/ufw.conf").contains(QRegularExpression("^ENABLED=yes", QRegularExpression::MultilineOption));
        return QVariantMap{{"installed", installed},
                           {"enabled", configured && output("systemctl", {"is-active", "ufw"}) == "active"},
                           {"rules", rules}};
    }
    if (name == "printers") {
        QVariantList printers;
        const QString def = output("lpstat", {"-d"}).section(':', 1).trimmed();
        static const QRegularExpression row(R"(^printer (\S+) (.*)$)");
        QStringList names;
        for (const QString &line : output("lpstat", {"-p"}).split('\n')) {
            const auto m = row.match(line);
            if (!m.hasMatch())
                continue;
            names << m.captured(1);
            printers << QVariantMap{{"name", m.captured(1)}, {"state", m.captured(2).section('.', 0, 0)},
                                    {"isDefault", m.captured(1) == def}, {"added", true}};
        }
        // Printers on the network that print without drivers (IPP
        // Everywhere) can be used straight away.
        for (const QString &n : output("lpstat", {"-e"}, 10000).split('\n', Qt::SkipEmptyParts))
            if (!names.contains(n))
                printers << QVariantMap{{"name", n}, {"state", ""}, {"isDefault", n == def}, {"added", false}};
        return QVariantMap{{"cups", output("systemctl", {"is-active", "cups"}) == "active"},
                           {"installed", !QStandardPaths::findExecutable("lpstat").isEmpty()}, {"printers", printers}};
    }
    if (name == "storage") {
        QVariantList volumes;
        QStringList devices;
        for (const QStorageInfo &v : QStorageInfo::mountedVolumes()) {
            const QString fs = QString::fromUtf8(v.fileSystemType());
            if (!v.isValid() || !v.isReady() || v.bytesTotal() < 1e9 || !v.device().startsWith("/dev/")
                || devices.contains(QString::fromUtf8(v.device())) || fs == "squashfs")
                continue;
            devices << QString::fromUtf8(v.device());
            volumes << QVariantMap{{"name", v.rootPath() == "/" ? tr("System") : v.displayName()}, {"path", v.rootPath()},
                                   {"total", double(v.bytesTotal())}, {"free", double(v.bytesAvailable())}, {"fs", fs}};
        }
        return QVariantMap{{"volumes", volumes}, {"snapper", !QStandardPaths::findExecutable("snapper").isEmpty()}};
    }
    if (name == "homeUsage") {
        // On request only: adding up a home folder can take a while.
        QVariantList out;
        QDir home(QDir::homePath());
        QStringList targets;
        for (const QString &e : home.entryList(QDir::Dirs | QDir::NoDotAndDotDot | QDir::Hidden | QDir::NoSymLinks))
            targets << home.filePath(e);
        const ProcResult r = run("du", QStringList{"-xsb", "--"} + targets, 180000);
        for (const QString &line : QString::fromUtf8(r.out).split('\n', Qt::SkipEmptyParts)) {
            const double bytes = line.section('\t', 0, 0).toDouble();
            if (bytes >= 50e6)
                out << QVariantMap{{"name", QFileInfo(line.section('\t', 1)).fileName()}, {"bytes", bytes}};
        }
        std::sort(out.begin(), out.end(), [](const QVariant &a, const QVariant &b) {
            return a.toMap().value("bytes").toDouble() > b.toMap().value("bytes").toDouble();
        });
        const double cache = output("du", {"-sb", "/var/cache/pacman/pkg"}, 60000).section('\t', 0, 0).toDouble();
        return QVariantMap{{"folders", out.mid(0, 12)}, {"packageCache", cache}};
    }
    if (name == "snapshots") {
        // snapper keeps its list for root; asking shows the polkit prompt.
        const ProcResult r = run("pkexec", {"snapper", "--csvout", "-c", "root", "list", "--columns", "number,date,description"}, 120000);
        QVariantList out;
        const QStringList lines = QString::fromUtf8(r.out).split('\n', Qt::SkipEmptyParts);
        for (int i = 1; i < lines.size(); ++i) {
            const QStringList f = lines[i].split(',');
            if (f.size() >= 3 && f[0] != "0")
                out.prepend(QVariantMap{{"number", f[0]}, {"date", f[1]}, {"description", f.mid(2).join(',')}});
        }
        return QVariantMap{{"ok", r.ok()}, {"error", r.ok() ? QString() : r.failure("snapper")}, {"snapshots", out}};
    }
    if (name == "managed") {
        // Everything Settings has changed, so it can be seen and undone.
        const QJsonObject state = managedState();
        QVariantList out;
        QHash<QString, QString> labels;
        for (const Setting &s : m_settings)
            if (!s.hyprOption.isEmpty())
                labels.insert(s.hyprOption, s.label);
        const QJsonObject hypr = state.value("hypr").toObject();
        for (auto it = hypr.begin(); it != hypr.end(); ++it)
            out << QVariantMap{{"kind", "hypr"}, {"key", it.key()}, {"label", labels.value(it.key(), it.key())},
                               {"value", it.value().toVariant()}};
        const QJsonObject monitors = state.value("monitors").toObject();
        for (auto it = monitors.begin(); it != monitors.end(); ++it)
            out << QVariantMap{{"kind", "monitor"}, {"key", it.key()}, {"label", QString(it.key()).remove(QRegularExpression("^desc:"))},
                               {"value", it.value().toObject().value("disabled").toBool() ? QStringLiteral("off")
                                                                                          : it.value().toObject().value("mode").toString()}};
        const QJsonObject workspaces = state.value("workspaces").toObject();
        for (auto it = workspaces.begin(); it != workspaces.end(); ++it)
            out << QVariantMap{{"kind", "workspace"}, {"key", it.key()},
                               {"label", it.value().toString().remove(QRegularExpression("^desc:"))}, {"value", it.key()}};
        if (state.contains("primary"))
            out << QVariantMap{{"kind", "primary"}, {"key", "primary"},
                               {"label", state.value("primary").toString().remove(QRegularExpression("^desc:"))}, {"value", ""}};
        for (const QJsonValue &b : state.value("bindings").toArray())
            out << QVariantMap{{"kind", "binding"}, {"key", b.toObject().value("keys")}, {"label", b.toObject().value("keys")},
                               {"value", b.toObject().value("description")}};
        for (const QJsonValue &k : state.value("unbinds").toArray())
            out << QVariantMap{{"kind", "unbind"}, {"key", k.toString()}, {"label", k.toString()}, {"value", "off"}};
        for (const QJsonValue &a : state.value("autostart").toArray())
            out << QVariantMap{{"kind", "autostart"}, {"key", a.toObject().value("command")}, {"label", a.toObject().value("name")},
                               {"value", a.toObject().value("command")}};
        const QJsonArray rules = state.value("windowRules").toArray();
        for (int i = 0; i < rules.size(); ++i)
            out << QVariantMap{{"kind", "rule"}, {"key", QString::number(i)},
                               {"label", rules[i].toObject().value("class").toString(rules[i].toObject().value("title").toString())},
                               {"value", ""}};
        if (state.value("gestures").toObject().value("workspaceSwipe").toBool())
            out << QVariantMap{{"kind", "gesture"}, {"key", "workspaceSwipe"}, {"label", "Swipe between workspaces"}, {"value", true}};
        if (state.value("nightShift").toObject().value("schedule").toBool())
            out << QVariantMap{{"kind", "nightShift"}, {"key", "schedule"}, {"label", "Night Shift schedule"},
                               {"value", state.value("nightShift").toObject().value("start").toString() + "–"
                                         + state.value("nightShift").toObject().value("end").toString()}};
        return out;
    }
    return {};
}

